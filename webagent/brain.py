# ---------------------------------------------------------------- QC
QC_SCHEMA = _obj({"ok": {"type": "boolean"}, "issues": {"type": "array", "items": S}, "fix": S})

QC_RULES = """Fail (ok=false) only for clear defects a viewer would notice:
- deformed or extra hands/fingers/limbs, melted or distorted faces, faces too small/blurred to read in a shot
  meant to show a face
- wrong person: a member does not match their reference portrait (hair colour/cut, outfit), or a member is missing,
  or an extra unexplained person appears (crowd in the audience is fine)
- members not standing ON the stage when the shot is supposed to be on stage
- visible text/letters, faces or people shown on screens/LED walls, microphones
- (video) the camera drifts so far that the shot loses its subject, a member walks out of frame, the image
  blows out to white/black for most of the shot, sudden morphing
Minor stylistic imperfections are fine. fix: a short phrase to ADD to the prompt that would avoid the defect
(e.g. "static tripod shot, both stay in place"), or "" when ok."""


def _continuity(shot):
    prev = shot.get("prev_state")
    if not prev:
        return ""
    return (f"\nContinuity: these members' previous shot ended with: {prev}. Fail only for a clear contradiction "
            "a viewer would notice at the cut (outfit or accessory changed, members swapped sides); a different "
            "camera angle or a small change of pose is fine.")


def qc_frame(shot, frame_path, ref_paths):
    content = []
    for name, p in ref_paths.items():
        content += [{"type": "text", "text": f"Reference portrait of {name}:"}, _image_block(p, 384)]
    content += [{"type": "text", "text": "Generated first frame:"}, _image_block(frame_path)]
    content.append({"type": "text", "text": (
        f"Shot {shot['id']} ({shot['shot']}, members: {', '.join(shot['members']) or 'none'}).\n"
        f"Intended: {shot['frame']['prompt']}{_continuity(shot)}\n\n{QC_RULES}")})
    return _call("You are the quality checker of an AI music video pipeline. Judge the still frame.",
                 content, QC_SCHEMA, effort="low", max_tokens=8000, task="qc")


