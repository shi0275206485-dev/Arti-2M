"""Claude API calls for the MV agent: concept, shot design, reference pick, frame/clip QC.

All calls stream (long outputs), use structured JSON output, adaptive thinking, and the
server-side refusal fallback. Every function returns plain dicts.
"""
import base64
import io
import json
from pathlib import Path

import anthropic
from PIL import Image

MODEL = "claude-opus-5-5"
BETAS = ["server-side-fallback-2026-07-01"]

_client = None
_api_key = None


def set_api_key(key):
    global _client, _api_key
    _api_key = key or None
    _client = None


def client():
    global _client
    if _client is None:
        _client = anthropic.Anthropic(api_key=_api_key) if _api_key else anthropic.Anthropic()
    return _client


def status():
    try:
        c = client()
        if not (c.api_key or getattr(c, "auth_token", None)):
            return {"ok": False, "error": "no ANTHROPIC_API_KEY / ANTHROPIC_AUTH_TOKEN"}
        return {"ok": True}
    except Exception as e:  # missing credentials raise at construction
        return {"ok": False, "error": str(e)}


def _image_block(path, max_side=768):
    im = Image.open(path).convert("RGB")
    im.thumbnail((max_side, max_side))
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=85)
    return {"type": "image", "source": {"type": "base64", "media_type": "image/jpeg",
                                        "data": base64.standard_b64encode(buf.getvalue()).decode()}}


def _call(system, content, schema, effort="high", max_tokens=32000):
    with client().beta.messages.stream(
        model=MODEL,
        max_tokens=max_tokens,
        betas=BETAS,
        fallbacks="default",
        thinking={"type": "adaptive"},
        output_config={"effort": effort, "format": {"type": "json_schema", "schema": schema}},
        system=system,
        messages=[{"role": "user", "content": content}],
    ) as stream:
        msg = stream.get_final_message()
    if msg.stop_reason == "refusal":
        raise RuntimeError(f"Claude declined the request ({getattr(msg.stop_details, 'category', None)})")
    if msg.stop_reason == "max_tokens":
        raise RuntimeError("Claude's answer was cut off (max_tokens)")
    text = next(b.text for b in msg.content if b.type == "text")
    return json.loads(text)


def _obj(props, required=None):
    return {"type": "object", "properties": props, "required": required or list(props),
            "additionalProperties": False}


S = {"type": "string"}

# ---------------------------------------------------------------- concept
CONCEPT_SCHEMA = _obj({
    "title": S,
    "style": S,
    "lyrics": S,
    "members": {"type": "array", "items": _obj({
        "name": S, "noun": {"type": "string", "enum": ["woman", "man"]},
        "look": S, "signature_color": S, "video_desc": S})},
    "frame_style": S,
    "video_style": S,
    "stage_plate": S,
    "lights": {"type": "array", "items": _obj({"key": S, "description": S})},
})

CONCEPT_SYSTEM = """You are the creative director of an automated local music-video pipeline.
The song is generated by YuE2 and the MV by Qwen Image 2.1 (first frames) + LTX-2.3 (image-to-video and
audio-driven lip-sync) on a single 16GB GPU. Write a concept that this pipeline can actually execute well.

Hard-won rules (from previous productions):
- The MV is a PERFORMANCE video on ONE fixed stage set. No story, no location changes; progression comes from lighting.
- No dancing (small video models deform bodies). Singing with small natural gestures and interaction between members.
- 1-2 members. Each member must have a very distinctive, fixed look (hair colour/cut, outfit, signature colour) so
  the image model keeps them consistent. Do not use the names of real artists.
- style: YuE2 tag string: genre, instruments, vocal type and gender, language(s), mood, "<N> BPM".
- lyrics: real lyrics with section tags on their own line: [Intro] [Verse] [Pre-Chorus] [Chorus] [Rap] [Bridge]
  [Outro] etc. Aim for a 2:30-3:30 song: intro, 2 verses, pre-choruses, 2-3 choruses, a bridge, an outro.
  Instrumental sections are written as a tag with no lines. Keep lines short and singable.
- members[].look: one dense sentence for a reference portrait (age, ethnicity, face, eyes, hair, accessories,
  outfit, glowing details). video_desc: a short identifying phrase, e.g. "the woman with the silver-white bob and
  black techwear jacket".
- frame_style: style suffix for still frames (camera, lens, grain, "photorealistic, no text, no watermark").
  video_style: one short sentence for the video model.
- stage_plate: an EMPTY stage seen from the audience pit at the front edge of a raised stage, so performers are
  later placed ON the stage floor with the back wall close behind them. Include "empty stage with no people,
  no letters, no signage". Avoid screens that could show faces or text: describe their content as abstract light.
- lights: 6-8 named lighting states (key like DARK, BUILD, FULL, SPOT, STROBE, FINALE), each a short phrase
  describing the stage lighting only (not the location)."""


def concept(brief, song=None):
    """song: an existing song from the music studio ({title, style, lyrics}); its words are kept as they are
    and only the visual concept is designed around it."""
    text = "Brief from the user:\n" + (brief.strip() or "(no brief: base the concept on the song)")
    if song:
        text += ("\n\nThe song ALREADY EXISTS and must not change. Copy its title, style and lyrics into your answer "
                 "exactly as given and design the members, looks, stage and lights to fit it. Choose the number and "
                 "gender of members from the vocals it describes (e.g. one female vocal -> one woman)."
                 f"\n\nTitle: {song.get('title', '')}\nStyle: {song.get('style', '') or '(unknown)'}\nLyrics:\n"
                 + (song.get("lyrics") or "(no lyrics available)"))
        if song.get("instrumental"):
            text += ("\n\nThe song is INSTRUMENTAL (no vocals): nobody sings or lip-syncs. lyrics must be an empty "
                     "string. Members perform through presence, looks, small natural movement and interaction with "
                     "each other and the light; no instruments in their hands, no microphones.")
    c = _call(CONCEPT_SYSTEM, [{"type": "text", "text": text}], CONCEPT_SCHEMA, effort="high")
    if song:
        c.update(title=song.get("title") or c["title"], style=song.get("style") or c["style"],
                 lyrics=song.get("lyrics") or "")
    return c


# ---------------------------------------------------------------- song (music studio)
def _song_schema():
    from .studio import OPTIONS   # one list for the page, the server and Claude
    enum = lambda k: {"type": "string", "enum": [""] + OPTIONS[k]}  # noqa: E731
    arr = lambda k: {"type": "array", "items": {"type": "string", "enum": OPTIONS[k]}}  # noqa: E731
    return _obj({"title": S, "style": S, "lyrics": S, "instrumental": {"type": "boolean"},
                 "settings": _obj({"genre_text": S, "vocal": enum("vocal"), "language": enum("language"),
                                   "moods": arr("moods"), "instruments": arr("instruments"),
                                   "bpm": {"type": "integer"}, "length": enum("length")})})


LENGTHS = {"short": "a 1:30-2:00 song: intro, verse, chorus, verse, chorus, outro",
           "standard": "a 2:30-3:30 song: intro, 2 verses, pre-choruses, 2-3 choruses, a bridge, an outro",
           "long": "a 4:00-4:30 song: intro, 3 verses, pre-choruses, 3 choruses, a bridge, a final chorus, an outro"}

SONG_SYSTEM = """You are a songwriter for an AI music generator ({engine}). From the user's brief write one song.
- title: short song title (no names of real artists or songs).
- style: tag string for the generator: genre, key instruments, vocal type and gender, language(s), mood, "<N> BPM".
  At most 300 characters.
- lyrics: real, singable lyrics in the language(s) the brief asks for, with section tags on their own line:
  [Intro] [Verse] [Pre-Chorus] [Chorus] [Rap] [Bridge] [Outro] etc. Aim for {length}.
  Instrumental sections are a tag with no lines. Short lines.
  Never quote or imitate the lyrics of existing songs.
- instrumental: true when the brief asks for music without vocals (instrumental, BGM, no singing, 纯音乐 ...).
  Then lyrics is an empty string and style names the lead instruments instead of a vocal, starting with
  "Instrumental," and ending with "no vocals".
- settings: the same choices in structured form, consistent with style (the user can change them by clicking):
  genre_text = short sub-genre phrase (e.g. "Mandopop ballad", "melodic techno"); vocal and language from the
  lists ("" when instrumental); 1-3 moods; 2-6 instruments; bpm = the tempo in style; length = the chosen length.
  When the user fixed some settings, use exactly those values and build style and lyrics around them."""


def song_draft(brief, engine="YuE2", instrumental=False, genre=None, settings=None):
    text = "Brief from the user:\n" + (brief or "(none: write an original song that fits the category below)")
    if genre:
        text += (f"\n\nMusic category chosen by the user (from Spotify's categories): {genre.get('name')}"
                 + (f" / {genre['name_zh']}" if genre.get("name_zh") and genre["name_zh"] != genre.get("name") else "")
                 + (f"\nTypical style tags for it: {genre['style']}" if genre.get("style") else "")
                 + "\nThe song must clearly belong to this category; the brief adds detail on top of it.")
    fixed = {k: v for k, v in (settings or {}).items() if v not in ("", None, [])}
    if fixed:
        text += "\n\nSettings the user already chose (keep these exactly): " + json.dumps(fixed, ensure_ascii=False)
    if instrumental:
        text += "\n\nThe user marked this song as INSTRUMENTAL: set instrumental=true and leave lyrics empty."
    length = (settings or {}).get("length") or "standard"
    r = _call(SONG_SYSTEM.format(engine=engine, length=LENGTHS[length]), [{"type": "text", "text": text}],
              _song_schema(), effort="medium", max_tokens=16000)
    r["settings"]["length"] = r["settings"].get("length") or length
    if instrumental:
        r.update(instrumental=True, lyrics="")
    return r


GENRE_SCHEMA = _obj({"items": {"type": "array", "items": _obj({
    "id": S, "style": S, "instrumental": {"type": "boolean"}})}})

GENRE_SYSTEM = """You map music-streaming categories (genres, moods, activities) to prompts for AI music generators
(YuE2 / Suno). For EVERY category given, return:
- id: the category id exactly as given.
- style: a generic style tag string (max 160 characters) a generator understands: sub-genre, 3-4 typical
  instruments, typical vocal (or "instrumental"), mood, and a typical "<N> BPM". For moods/activities
  (Chill, Workout, Sleep, Focus, Party ...) pick the music people usually play for it. For regional categories
  (K-Pop, Mandopop, Latin, Afro ...) name the language of the vocals. Never name real artists or songs.
- instrumental: true when the category is usually music without vocals (sleep, focus, classical, ambient,
  lo-fi study ...), else false."""


def genre_styles(categories):
    """{id: {"style", "instrumental"}} for Spotify categories (one call for the whole list)."""
    listing = "\n".join(f"{c['id']}: {c['name']}" + (f" ({c['name_zh']})" if c.get("name_zh") else "")
                        for c in categories)
    r = _call(GENRE_SYSTEM, [{"type": "text", "text": "Categories:\n" + listing}], GENRE_SCHEMA,
              effort="low", max_tokens=16000)
    return {i["id"]: {"style": i["style"], "instrumental": i["instrumental"]} for i in r["items"]}


# ---------------------------------------------------------------- shot design
SIZES = ["close-up", "medium close-up", "medium", "wide"]
KINDS = ["solo", "duo", "stage_wide", "back_view", "empty"]
DESIGN_SCHEMA = _obj({"rows": {"type": "array", "items": _obj({
    "first_bar": {"type": "integer"}, "last_bar": {"type": "integer"},
    "kind": {"type": "string", "enum": KINDS},
    "members": {"type": "array", "items": S},
    "lipsync": {"anyOf": [{"type": "string"}, {"type": "null"}]},
    "size": {"type": "string", "enum": SIZES},
    "light": S,
    "action": S,
    "motion": S,
})}})

DESIGN_SYSTEM = """You are the shot designer of an automated performance-MV pipeline (Qwen Image 2.1 first frames,
LTX-2.3 video at 1280x720, ~2-4 s per shot). You receive the song's bar grid and design one shot per row so that
the rows cover EVERY bar exactly once, in order, with no gaps or overlaps (first_bar..last_bar inclusive).

Rules (each learned from a failed render; follow them strictly):
- Cut on bar lines. Shots are 1 or 2 bars (3 only for slow intros/outros). Choruses cut faster (mostly 1-2 bars).
- kind: solo (one member), duo (two members together), stage_wide (both small on the stage seen from the crowd,
  to establish they are ON the stage; use sparingly, ~1 per section), back_view (members seen from behind facing
  the crowd; no faces needed), empty (no members: lights, LED wall, crowd, sparks inserts).
- members: names from the member list; solo = 1, duo/stage_wide/back_view = 2, empty = [].
- lipsync: the member whose mouth is driven by the vocal in this shot, or null. Only on bars where vocal=true.
  The song has one lead voice; split lines between members K-pop style (alternate lines/sections) and use duo
  shots with lipsync set to one member and motion "both sing the same line together" for unison moments.
  Never lipsync on stage_wide/back_view/empty shots. Most vocal bars should be lip-sync shots.
- size: close-up / medium close-up for singing; medium (waist-up) for duos and gestures; wide only for
  stage_wide/back_view/empty. People are never framed wider than medium except stage_wide/back_view.
- NO dancing. Allowed: singing with small head moves, smiling, a brief glance at each other and back to the
  camera, standing shoulder to shoulder, arm around the shoulder (in the FIRST FRAME pose, not as a motion).
- Duo motion must keep both bodies facing the camera the whole shot. The video model turns any "lean
  together / turn to each other / back to back" motion into profiles, kisses or hugs that hide the faces, so
  put interaction into the static pose and keep the motion to singing, smiling and small head moves.
- Hands: never make hands the subject (no reaching to camera, no fingertip touches, no hand inserts, no
  microphones). Mediums keep arms relaxed or hands in pockets.
- Never ask a screen to show faces, people or text. Describe screens as abstract light.
- Camera: prefer "static tripod shot"; never "pull back" or "push in" on people (the model drifts wide or
  crops too close).
- light: one of the given lighting keys, following the song's energy arc.
- action: what is in the first frame, as a short clause using member NAMES (e.g. "NOVA singing toward ECHO,
  who smiles back"). For empty shots: the full description of the insert (stage, lights, crowd...).
- motion: what moves during the shot, one sentence, using names."""


def design(bars_text, members, lights, feedback=None):
    content = (f"Members: {', '.join(members)}\nLighting keys: {', '.join(lights)}\n\n"
               f"Bar grid (index, section, vocal, energy, lyric):\n{bars_text}")
    if feedback:
        content += f"\n\nYour previous design had problems, fix them:\n{feedback}"
    return _call(DESIGN_SYSTEM, [{"type": "text", "text": content}], DESIGN_SCHEMA,
                 effort="high", max_tokens=64000)["rows"]


# ---------------------------------------------------------------- reference pick
PICK_SCHEMA = _obj({"best": {"type": "integer"}, "reason": S})


def pick_reference(look, paths):
    content = []
    for i, p in enumerate(paths):
        content += [{"type": "text", "text": f"Candidate {i}:"}, _image_block(p, 512)]
    content.append({"type": "text", "text": (
        f"Target look: {look}\nPick the candidate that best matches the look, has a clean front-facing sharp face, "
        "no artifacts, no text, plain background. Return its index.")})
    return _call("You choose character reference portraits for an AI music video.", content,
                 PICK_SCHEMA, effort="low", max_tokens=4000)


# ---------------------------------------------------------------- QC
QC_SCHEMA = _obj({"ok": {"type": "boolean"}, "issues": {"type": "array", "items": S}, "fix": S})

QC_RULES = """Fail (ok=false) only for clear defects a viewer would notice:
- deformed or extra hands/fingers/limbs, melted or distorted faces, faces too small/blurred to read in a shot
  meant to show a face
- wrong person: a member does not match their reference portrait (hair colour/cut, outfit), or a member is missing,
  or an extra unexplained person appears (crowd in the audience is fine)
- members not standing ON the stage when the shot is supposed to be on stage
- visible text/letters, faces or people shown on screens/LED walls, microphones
- (video) the camera drifts so far that the shot loses its subject, a member walks out of frame, the image
  blows out to white/black for most of the shot, sudden morphing
Minor stylistic imperfections are fine. fix: a short phrase to ADD to the prompt that would avoid the defect
(e.g. "static tripod shot, both stay in place"), or "" when ok."""


def qc_frame(shot, frame_path, ref_paths):
    content = []
    for name, p in ref_paths.items():
        content += [{"type": "text", "text": f"Reference portrait of {name}:"}, _image_block(p, 384)]
    content += [{"type": "text", "text": "Generated first frame:"}, _image_block(frame_path)]
    content.append({"type": "text", "text": (
        f"Shot {shot['id']} ({shot['shot']}, members: {', '.join(shot['members']) or 'none'}).\n"
        f"Intended: {shot['frame']['prompt']}\n\n{QC_RULES}")})
    return _call("You are the quality checker of an AI music video pipeline. Judge the still frame.",
                 content, QC_SCHEMA, effort="low", max_tokens=8000)


def qc_clip(shot, sample_paths, ref_paths):
    content = []
    for name, p in ref_paths.items():
        content += [{"type": "text", "text": f"Reference portrait of {name}:"}, _image_block(p, 384)]
    for label, p in sample_paths:
        content += [{"type": "text", "text": f"Video frame at {label}:"}, _image_block(p, 640)]
    content.append({"type": "text", "text": (
        f"Shot {shot['id']} ({shot['shot']}, members: {', '.join(shot['members']) or 'none'}).\n"
        f"Intended first frame: {shot['frame']['prompt']}\nIntended motion: {shot['video']['prompt']}\n\n"
        f"{QC_RULES}\nfix must be a MOTION prompt addition.")})
    return _call("You are the quality checker of an AI music video pipeline. Judge the video clip from its frames.",
                 content, QC_SCHEMA, effort="low", max_tokens=8000)
